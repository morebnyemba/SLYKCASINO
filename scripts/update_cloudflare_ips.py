#!/usr/bin/env python3
"""Refresh Cloudflare's IP ranges in the nginx real-IP config and the backend.

Cloudflare publishes its ranges at https://www.cloudflare.com/ips-v4 and
/ips-v6 and changes them rarely. Run this when they do, commit the result,
and redeploy (nginx and django):

    python3 scripts/update_cloudflare_ips.py
"""
from __future__ import annotations

import ipaddress
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
URLS = ('https://www.cloudflare.com/ips-v4', 'https://www.cloudflare.com/ips-v6')

NGINX = """# GENERATED by scripts/update_cloudflare_ips.py — edit that, not this.
#
# Real visitor IPs behind Cloudflare. Every request reaches nginx from a
# Cloudflare edge server, which puts the visitor's IP in CF-Connecting-IP.
# nginx takes it as $remote_addr ONLY when the request really comes from one of
# Cloudflare's ranges below (or REAL_IP_TRUSTED, e.g. a proxy in between), so
# anyone else sending the header is ignored. Every proxy_pass then forwards the
# real IP (X-Real-IP / X-Forwarded-For) to Django, which needs no other setting
# (TRUSTED_PROXY_COUNT stays 1).
#
# Not behind Cloudflare? This is harmless: no request comes from these ranges.

{lines}
set_real_ip_from ${{REAL_IP_TRUSTED}};
real_ip_header CF-Connecting-IP;
"""

PYTHON = '''"""GENERATED by scripts/update_cloudflare_ips.py — edit that, not this.

Cloudflare's edge ranges. An address in them is Cloudflare, never a player:
nginx resolves the real visitor IP (nginx/*/cloudflare-realip.conf.template),
and the fraud engine ignores any Cloudflare address recorded before that.
"""
import ipaddress
from functools import lru_cache

CLOUDFLARE_RANGES = (
{lines}
)


@lru_cache(maxsize=1)
def _networks():
    return tuple(ipaddress.ip_network(r) for r in CLOUDFLARE_RANGES)


def is_cloudflare(ip) -> bool:
    try:
        addr = ipaddress.ip_address(str(ip))
    except ValueError:
        return False
    return any(addr in net for net in _networks() if net.version == addr.version)
'''


def fetch() -> list[str]:
    ranges = []
    for url in URLS:
        req = urllib.request.Request(url, headers={'User-Agent': 'curl/8 (betblits update_cloudflare_ips)'})
        with urllib.request.urlopen(req, timeout=20) as res:  # noqa: S310 — fixed https URLs
            for line in res.read().decode().split():
                ranges.append(str(ipaddress.ip_network(line.strip())))  # validates each one
    if len(ranges) < 10:
        raise SystemExit(f'Only got {len(ranges)} ranges from Cloudflare — not writing anything.')
    return ranges


def main() -> None:
    ranges = fetch()
    nginx = NGINX.format(lines='\n'.join(f'set_real_ip_from {r};' for r in ranges))
    for folder in ('nginx/prod', 'nginx/templates'):
        (ROOT / folder / 'cloudflare-realip.conf.template').write_text(nginx)
    (ROOT / 'backend/common/cloudflare.py').write_text(
        PYTHON.format(lines='\n'.join(f"    '{r}'," for r in ranges)))
    print(f'Wrote {len(ranges)} Cloudflare ranges.')


if __name__ == '__main__':
    main()
